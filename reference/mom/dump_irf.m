% dump_irf.m -- IRF-matching reference values of Dynare (7.2 by default, see DYNARE_VERSION) (stream MoM).
%
% 1. nk_irf.mod -DGEN: IRFs at the calibration; perturbed deterministically, they become the
%    "empirical" IRFs of nk_irf_data.inc (a matched_irfs block with values and weights).
% 2. nk_irf.mod -DCASE=k for k = 1..3: writes ref_nk_irf_case<k>.json (oo_.mom, the mode file,
%    the objective at fixed points) and nk_irf_case<k>_matlab.log.
%
% Run from a PRIVATE copy of reference/mom:
%   /Applications/MATLAB_R2025b.app/bin/matlab -batch "run('dump_irf.m')"
ver = getenv('DYNARE_VERSION'); if isempty(ver), ver = '7.2'; end % DYNARE_VERSION=7.1 for the 7.1 baseline
droot = getenv('DYNARE_ROOT'); if isempty(droot), droot = sprintf('/Applications/Dynare/%s-arm64', ver); end;
addpath(fullfile(droot, 'matlab'));
here = fileparts(mfilename('fullpath'));
cd(here);
if ~exist('cases', 'var'), cases = 1:3; end

if ~isfile('nk_irf_data.inc')
    dynare nk_irf -DGEN nointeractive
    fid = fopen('nk_irf_data.inc', 'w');
    fprintf(fid, '// generated by dump_irf.m from the IRFs of nk_irf.mod -DGEN (perturbed)\nmatched_irfs;\n');
    vars = {'y', 'pi', 'i'}; shocks = {'e_a', 'e_i'};
    for s = 1:numel(shocks)
        for v = 1:numel(vars)
            x = oo_.irfs.([vars{v} '_' shocks{s}]);
            per = 1:12;
            if s == 1 && v == 3, per = 2:10; end   % some gaps
            vals = x(per) .* (1 + 0.1*sin(per + v + 3*s));
            w = 1 ./ (0.05*abs(x(per)) + 0.01).^2;
            fprintf(fid, 'var %s; varexo %s;\nperiods %s;\nvalues %s;\nweights %s;\n', vars{v}, shocks{s}, ...
                    strjoin(arrayfun(@(p) sprintf('%d', p), per, 'UniformOutput', false), ', '), ...
                    strjoin(arrayfun(@(p) sprintf('%.17g', p), vals, 'UniformOutput', false), ', '), ...
                    strjoin(arrayfun(@(p) sprintf('%.17g', p), w, 'UniformOutput', false), ', '));
        end
    end
    fprintf(fid, 'end;\n');
    fclose(fid);
end

for k = cases
    clear global M_ options_ oo_ estim_params_ bayestopt_ options_mom_
    eval(sprintf('dynare nk_irf -DCASE=%d nointeractive', k));
    S = load(fullfile('nk_irf', 'method_of_moments', 'nk_irf_mom_results.mat'));
    om = S.options_mom_;
    R = struct();
    R.case = k;
    R.param_names = S.bayestopt_.name;
    R.irfIndex = om.mom.irfIndex;
    R.irf = om.irf;
    R.mom = S.oo_.mom;
    if isfield(R.mom, 'verbose') && isempty(R.mom.verbose), R.mom = rmfield(R.mom, 'verbose'); end
    MF = load(fullfile('nk_irf', 'method_of_moments', 'nk_irf_mode.mat'));
    R.mode_file = MF;
    np = numel(S.bayestopt_.name);
    BoundsInfo.lb = -Inf(np, 1); BoundsInfo.ub = Inf(np, 1);
    x0 = [S.estim_params_.var_exo(:, 2); S.estim_params_.param_vals(:, 2)];
    pts = {x0, x0 .* (1 + 0.02*(1:np)'), MF.xparam1};
    R.points = {};
    for j = 1:numel(pts)
        x = pts{j};
        P = struct('x', x);
        [P.fval, info, ~, ~, ~, P.Q, P.model_moments] = mom.objective_function(x, S.oo_.mom.data_moments, S.oo_.mom.weighting_info, om, S.M_, S.estim_params_, S.bayestopt_, BoundsInfo, S.oo_.dr, S.oo_.steady_state, S.oo_.exo_steady_state, S.oo_.exo_det_steady_state);
        P.info = info(1);
        R.points{end+1} = P;
    end
    R.mom.weighting_info.W = full(R.mom.weighting_info.W);
    R.mom.weighting_info.Winv = full(R.mom.weighting_info.Winv);
    R.matched_irfs = S.M_.matched_irfs;
    copyfile('nk_irf.log', sprintf('nk_irf_case%d_matlab.log', k));
    fid = fopen(sprintf('ref_nk_irf_case%d.json', k), 'w');
    fprintf(fid, '%s', jsonencode(unsparse(R), 'ConvertInfAndNaN', true));
    fclose(fid);
end

function s = unsparse(s)
    % jsonencode cannot write sparse matrices (W and everything computed with it)
    if issparse(s)
        s = full(s);
    elseif isstruct(s)
        for f = fieldnames(s)'
            for j = 1:numel(s)
                s(j).(f{1}) = unsparse(s(j).(f{1}));
            end
        end
    elseif iscell(s)
        for j = 1:numel(s)
            s{j} = unsparse(s{j});
        end
    end
end
