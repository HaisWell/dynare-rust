//! The `TeX` option's estimation tables: `<fname>_Posterior_Mode_<k>.tex`
//! (`display_estimation_results_table.m`, Bayesian branch) and `<fname>_Posterior_Mean_<k>.tex`
//! (`GetPosteriorParametersStatistics.m`), k = 1 parameters, 2 shock standard deviations,
//! 4 shock correlations.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Result;

use super::{datestr_now, endo_tex, exo_tex, fmt_f, latex_dir, param_tex};
use crate::estimation::{ParamMoments, Prior};
use crate::modfile::{EstimatedKind, EstimatedParam, ModFile};

/// `pnames{pshape+1}` of the estimation tables.
pub fn prior_short_name(code: u8) -> &'static str {
    match code {
        1 => "beta",
        2 => "gamm",
        3 => "norm",
        4 => "invg",
        5 => "unif",
        6 => "invg2",
        8 => "weibl",
        _ => "",
    }
}

/// (file number, title, member test) of the three groups.
const GROUPS: [(usize, &str); 5] = [
    (1, "parameters"),
    (2, "standard deviation of structural shocks"),
    (3, "standard deviation of measurement errors"),
    (4, "correlation of structural shocks"),
    (5, "correlation of measurement errors"),
];

fn group_of(e: &EstimatedParam) -> usize {
    match e.kind {
        EstimatedKind::Param(_) => 1,
        EstimatedKind::StdErr(_) => 2,
        EstimatedKind::Corr(..) => 4,
        EstimatedKind::MeStdErr(_) => 3,
        EstimatedKind::MeCorr(..) => 5,
        EstimatedKind::Skew(_) => 2,      // listed with the shocks
        EstimatedKind::InitState(_) => 6, // ---- estimation completion
    }
}

fn end(s: &mut String) {
    s.push_str("\\end{longtable}\n \\end{center}\n% End of TeX file.\n");
}

/// Writes `<fname>_Posterior_Mode_{1,2,4}.tex` for the groups that have estimated parameters.
/// `est`/`priors`/`mode`/`sd` are in `xparam1` order.
pub fn posterior_mode(
    mf: &ModFile,
    est: &[EstimatedParam],
    priors: &[Prior],
    mode: &[f64],
    sd: &[f64],
    dir: &Path,
    fname: &str,
) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for (num, title) in GROUPS {
        let idx: Vec<usize> = (0..est.len()).filter(|&k| group_of(&est[k]) == num).collect();
        if idx.is_empty() {
            continue;
        }
        let mut s = String::new();
        s.push_str("% TeX-table generated by dynare_estimation (Dynare).\n");
        let _ = writeln!(s, "% RESULTS FROM POSTERIOR MAXIMIZATION ({title})");
        let _ = write!(s, "% {} \n \n", datestr_now());
        s.push_str("\\begin{center}\n\\begin{longtable}{llcccc} \n");
        let _ = write!(s, "\\caption{{Results from posterior maximization ({title})}}\\\\\n ");
        let _ = writeln!(s, "\\label{{Table:Posterior:{num}}}\\\\");
        let head = "  & \\multicolumn{3}{c}{Prior}  &  \\multicolumn{2}{c}{Posterior} \\\\\n  \\cmidrule(r{.75em}){2-4} \\cmidrule(r{.75em}){5-6}\n  & Dist. & Mean  & Stdev & Mode & Stdev \\\\ \n";
        s.push_str("\\toprule \n");
        s.push_str(head);
        s.push_str("\\midrule \\endfirsthead \n\\caption{(continued)}\\\\\n \\bottomrule \n");
        s.push_str(head);
        s.push_str("\\midrule \\endhead \n\\bottomrule \\multicolumn{6}{r}{(Continued on next page)}\\endfoot \n\\bottomrule\\endlastfoot \n");
        for k in idx {
            let p = &priors[k];
            let (name, dist) = match est[k].kind {
                EstimatedKind::Param(i) => (param_tex(mf, i), prior_short_name(p.shape.code()).to_string()),
                EstimatedKind::StdErr(e) => (exo_tex(mf, e), format!("{:>4}", prior_short_name(p.shape.code()))),
                EstimatedKind::Corr(a, b) => {
                    (format!("{},{}", exo_tex(mf, a), exo_tex(mf, b)), prior_short_name(p.shape.code()).to_string())
                }
                EstimatedKind::MeStdErr(e) => (endo_tex(mf, e), format!("{:>4}", prior_short_name(p.shape.code()))),
                EstimatedKind::MeCorr(a, b) => {
                    (format!("{},{}", endo_tex(mf, a), endo_tex(mf, b)), prior_short_name(p.shape.code()).to_string())
                }
                EstimatedKind::Skew(e) => {
                    (format!("skew {}", exo_tex(mf, e)), prior_short_name(p.shape.code()).to_string())
                }
                EstimatedKind::InitState(e) => {
                    (format!("init {}", endo_tex(mf, e)), prior_short_name(p.shape.code()).to_string())
                } // ---- estimation completion
            };
            let _ = writeln!(
                s,
                "${}$ & {} & {} & {} & {} & {} \\\\ ",
                name,
                dist,
                fmt_f(p.mean, 7, 3),
                fmt_f(p.sd, 6, 4),
                fmt_f(mode[k], 8, 4),
                fmt_f(sd[k], 7, 4)
            );
        }
        end(&mut s);
        let path = latex_dir(dir, fname)?.join(format!("{fname}_Posterior_Mode_{num}.tex"));
        std::fs::write(&path, s)?;
        out.push(path);
    }
    Ok(out)
}

/// Writes `<fname>_Posterior_Mean_{1,2,4}.tex` (after an MCMC).
pub fn posterior_mean(
    mf: &ModFile,
    est: &[EstimatedParam],
    priors: &[Prior],
    moments: &[ParamMoments],
    dir: &Path,
    fname: &str,
) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for (num, title) in GROUPS {
        let idx: Vec<usize> = (0..est.len()).filter(|&k| group_of(&est[k]) == num).collect();
        if idx.is_empty() {
            continue;
        }
        let mut s = String::new();
        s.push_str("% TeX-table generated by Dynare.\n");
        let _ = writeln!(s, "% RESULTS FROM METROPOLIS HASTINGS ({title})");
        let _ = write!(s, "% {} \n \n", datestr_now());
        s.push_str("\\begin{center}\n\\begin{longtable}{llcccccc} \n");
        let _ = write!(s, "\\caption{{Results from Metropolis-Hastings ({title})}}\n ");
        let _ = writeln!(s, "\\label{{Table:MHPosterior:{num}}}\\\\");
        let head = "  & \\multicolumn{3}{c}{Prior}  &  \\multicolumn{4}{c}{Posterior} \\\\\n  \\cmidrule(r{.75em}){2-4} \\cmidrule(r{.75em}){5-8}\n  & Dist. & Mean  & Stdev. & Mean & Stdev. & HPD inf & HPD sup\\\\\n";
        s.push_str("\\toprule \n");
        s.push_str(head);
        s.push_str("\\midrule \\endfirsthead \n\\caption{(continued)}\\\\\\toprule \n");
        s.push_str(head);
        s.push_str("\\midrule \\endhead \n\\bottomrule \\multicolumn{8}{r}{(Continued on next page)} \\endfoot \n\\bottomrule \\endlastfoot \n");
        for k in idx {
            let p = &priors[k];
            let m = &moments[k];
            let name = match est[k].kind {
                EstimatedKind::Param(i) => param_tex(mf, i),
                EstimatedKind::StdErr(e) => exo_tex(mf, e),
                EstimatedKind::Corr(a, b) => format!("({},{})", exo_tex(mf, a), exo_tex(mf, b)),
                EstimatedKind::MeStdErr(e) => endo_tex(mf, e),
                EstimatedKind::MeCorr(a, b) => format!("({},{})", endo_tex(mf, a), endo_tex(mf, b)),
                EstimatedKind::Skew(e) => format!("skew {}", exo_tex(mf, e)),
                EstimatedKind::InitState(e) => format!("init {}", endo_tex(mf, e)), // ---- estimation completion
            };
            let _ = writeln!(
                s,
                "${}$ & {} & {} & {} & {}& {} & {} & {} \\\\ ",
                name,
                prior_short_name(p.shape.code()),
                fmt_f(p.mean, 7, 3),
                fmt_f(p.sd, 6, 4),
                fmt_f(m.mean, 7, 3),
                fmt_f(m.var.sqrt(), 6, 4),
                fmt_f(m.hpd.0, 7, 4),
                fmt_f(m.hpd.1, 7, 4)
            );
        }
        end(&mut s);
        let path = latex_dir(dir, fname)?.join(format!("{fname}_Posterior_Mean_{num}.tex"));
        std::fs::write(&path, s)?;
        out.push(path);
    }
    Ok(out)
}
